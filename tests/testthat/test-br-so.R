test_that("BR-SO-08: The set of scatter plots is filtered to show only plots relevant to the selected 'Group Level'.", {
  skip_on_cran()
  app <- AppDriver$new(
    app_dir = test_path("apps", "standard"),
    variant = "br",
    name = "so-08",
    width = 1300,
    height = 800
  )
  app$wait_for_idle()
  app$set_inputs(`study_overview-nav_bar` = "Scatter Plots")
  app$wait_for_idle()

  # Check visibility for "Site"
  site_plot_selector <- "#study_overview-scatter-Analysis_kri0001"
  country_plot_selector <- "#study_overview-scatter-Analysis_kri0004"
  expect_false(app$get_element(selector = paste0(site_plot_selector, " .chart"))$is_hidden())
  expect_true(app$get_element(selector = paste0(country_plot_selector, " .chart"))$is_hidden())

  # Change to "Country" and check visibility
  app$set_inputs(`group-level-select` = "Country")
  app$wait_for_idle()
  expect_true(app$get_element(selector = paste0(site_plot_selector, " .chart"))$is_hidden())
  expect_false(app$get_element(selector = paste0(country_plot_selector, " .chart"))$is_hidden())

  app$stop()
})

