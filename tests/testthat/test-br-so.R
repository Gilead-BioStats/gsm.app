test_that("BR-SO-05: The flag status pills display a count of KRIs with that flag status for the selected 'Group Level'.", {
  skip_on_cran()
  app <- AppDriver$new(
    app_dir = test_path("apps", "standard"),
    variant = "br",
    name = "so-05",
    width = 1300,
    height = 800
  )
  app$wait_for_idle()

  # Check Site level counts
  site_results <- gsm.app::sample_dfResults %>%
    dplyr::filter(.data$GroupLevel == "Site") %>%
    gsm.kri::FilterByLatestSnapshotDate()
  red_count_site <- sum(abs(site_results$Flag) == 2)
  amber_count_site <- sum(abs(site_results$Flag) == 1)

  expect_equal(app$get_text("#study_overview-table-kri_counts-red-toggle_pill"), paste(red_count_site, "Red KRIs"))
  expect_equal(app$get_text("#study_overview-table-kri_counts-amber-toggle_pill"), paste(amber_count_site, "Amber KRIs"))

  # Check Country level counts
  app$set_inputs(`group-level-select` = "Country")
  app$wait_for_idle()

  country_results <- gsm.app::sample_dfResults %>%
    dplyr::filter(.data$GroupLevel == "Country") %>%
    gsm.kri::FilterByLatestSnapshotDate()
  red_count_country <- sum(abs(country_results$Flag) == 2)
  amber_count_country <- sum(abs(country_results$Flag) == 1)

  expect_equal(app$get_text("#study_overview-table-kri_counts-red-toggle_pill"), paste(red_count_country, "Red KRIs"))
  expect_equal(app$get_text("#study_overview-table-kri_counts-amber-toggle_pill"), paste(amber_count_country, "Amber KRIs"))

  app$stop()
})

